def _identity_inputs(scope: str, applicability: Mapping[str, Any]) -> dict[str, Any]:
    identity: dict[str, Any] = {
        "hdnt_no": None, "hdnt_date": None, "valid_from": None, "valid_to": None,
        "pl_no": None, "pl_date": None, "hdmb_no": None, "hdmb_date": None,
        "pxk_no": None, "pxk_date": None, "currency": "VND", "id": None,
    }
    state = {dt: getattr(applicability.get(dt), "state", None) for dt in (HDNT, PL, HDMB)}

    if state.get(HDNT) in (READY, MISSING_INFO):
        st.markdown("##### ✏️ HỢP ĐỒNG NGUYÊN TẮC (HDNT)")
        identity["hdnt_no"] = st.text_input("Số HDNT", key=f"docgen_hdntno_{scope}")
        identity["hdnt_date"] = st.date_input("Ngày ký HDNT", value=None, key=f"docgen_hdntdate_{scope}")
        left, right = st.columns(2)
        identity["valid_from"] = left.date_input("Hiệu lực từ", value=None, key=f"docgen_validfrom_{scope}")
        identity["valid_to"] = right.date_input("Hiệu lực đến", value=None, key=f"docgen_validto_{scope}")

    if state.get(PL) in (READY, MISSING_INFO):
        st.markdown("##### ✏️ PHỤ LỤC (PL)")
        identity["pl_no"] = st.text_input("Số PL", key=f"docgen_plno_{scope}")
        identity["pl_date"] = st.date_input("Ngày PL", value=None, key=f"docgen_pl_date_{scope}")

    if state.get(HDMB) in (READY, MISSING_INFO):
        st.markdown("##### ✏️ HỢP ĐỒNG MUA BÁN (HDMB)")
        identity["hdmb_no"] = st.text_input("Số HDMB", key=f"docgen_hdmbno_{scope}")
        identity["hdmb_date"] = st.date_input("Ngày HDMB", value=None, key=f"docgen_hdmb_date_{scope}")

    # Dates travel through MongoDB, so they are stored as ISO strings. A date
    # object would come back as a datetime and break the fail-closed HDNT
    # validity check (which parses with date.fromisoformat).
    for key in ("hdnt_date", "valid_from", "valid_to", "pl_date", "hdmb_date"):
        value = identity.get(key)
        if value is not None and not isinstance(value, str):
            identity[key] = value.isoformat()
    return identity


def _hdnt_reuse_block(scope: str, agent: Mapping[str, Any] | None, company: Mapping[str, Any] | None, contracts: Mapping[str, Any]) -> tuple[dict[str, Any] | None, dict[str, Any]]:
    """♻️ TÁI SỬ DỤNG HDNT — never silently picks the latest."""
    reuse: dict[str, Any] = {}
    if agent:
        reuse = gen.reuse_decision_for_agent(contracts, agent=agent, company=company)
    parent: dict[str, Any] | None = None

    st.markdown("##### ♻️ TÁI SỬ DỤNG HDNT")
    valid_count = int(reuse.get("valid_count", 0) or 0)
    if valid_count > 1:
        valid = reuse.get("valid_hdnt") or []
        labels = {str(c.get("id") or c.get("hdnt_no") or c.get("contract_no")): c for c in valid}
        chosen = st.selectbox(
            "Có nhiều HDNT hợp lệ — hãy chọn HDNT dùng cho hợp đồng này",
            [""] + list(labels.keys()),
            format_func=lambda k: k or "-- Chọn HDNT --",
            key=f"docgen_parent_{scope}",
        )
        parent = labels.get(chosen) if chosen else None
        st.caption("Không tự chọn HDNT mới nhất — Anh chọn HDNT cần dùng.")
    elif valid_count == 1:
        parent = reuse.get("reuse_target")
        st.success(
            "♻️ Có một HDNT hợp lệ đang dùng cho Đại lý + Công ty này: "
            f"**{parent.get('hdnt_no') or parent.get('contract_no') or parent.get('id')}** — sẽ tái sử dụng, không tạo HDNT mới."
        )
    else:
        st.caption("Chưa có HDNT hợp lệ cho Đại lý + Công ty này — sẽ tạo HDNT mới khi Anh bấm Xuất.")
    return parent, reuse


def _contract_identity_block(scope: str, item: Mapping[str, Any], applicability: Mapping[str, Any]) -> dict[str, Any]:
    """Identity inputs persisted on the contract record so nothing is lost."""
    stored = dict(item.get("doc_identity") or {})
    identity = _identity_inputs(scope, applicability)
    changed = False
    for key in ("hdnt_no", "hdnt_date", "valid_from", "valid_to", "pl_no", "pl_date", "hdmb_no", "hdmb_date"):
        value = identity.get(key)
        if value is not None and not isinstance(value, str) and hasattr(value, "isoformat"):
            value = value.isoformat()
        serialised = str(value) if value is not None else ""
        if stored.get(key) != serialised:
            stored[key] = serialised
            changed = True
    return identity, stored, changed


