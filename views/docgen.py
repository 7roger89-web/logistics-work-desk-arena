def _pxk_source_candidates(scope_ids: list[str]) -> list[dict[str, Any]]:
    """Explicit PXK source candidates (HDMB / PL) for this shipment / contract."""
    candidates: list[dict[str, Any]] = []
    seen: set[str] = set()
    for scope in scope_ids:
        for _id, doc in load_docgen_documents(scope).items():
            doc_type = str(doc.get("document_type") or "").upper()
            if doc_type not in (HDMB, PL):
                continue
            snapshot = doc.get("source_snapshot") or {}
            goods_lines = snapshot.get("goods_lines") or []
            record_id = str(doc.get("id") or "")
            if record_id in seen:
                continue
            seen.add(record_id)
            candidates.append(
                {
                    "source_document_type": doc_type,
                    "source_contract_id": str(doc.get("document_id") or "").strip(),
                    "source_revision": doc.get("generation_revision") or doc.get("revision") or 1,
                    "source_line_count": len(goods_lines),
                    "source_goods_line": list(goods_lines)[0] if goods_lines else {},
                    "label": f"{_DOC_LABEL.get(doc_type, doc_type)} {doc.get('document_id')} — {len(goods_lines)} dòng",
                }
            )
    return candidates


