def goods_totals_known(applicability: Mapping[str, Any]) -> bool:
    """True when the goods set produced a trustworthy total (not UNKNOWN)."""
    for doc_type in (HDNT, PL, HDMB):
        readiness = applicability.get(doc_type)
        if readiness is None:
            continue
        reason = str(getattr(readiness, "reason", "") or "")
        if "Chưa có tổng giá trị sau thuế đáng tin cậy" in reason:
            return False
        if getattr(readiness, "state", None) == BLOCKED and "Chưa có dòng hàng hóa mua nào" in reason:
            return False
    return True



# ---------------------------------------------------------------------------
# Goods entry — owner-first rows (no spreadsheet grid)
#
# The Owner is non-technical and uses a phone as often as a laptop, so goods
# are entered as plain rows: one clearly labelled control per column, STT
# numbered automatically, VAT locked at 8%, "Thành tiền" computed.  A blank
# quantity or price stays UNKNOWN and is never silently turned into 0.
# ---------------------------------------------------------------------------

_VAT_LOCKED = Decimal("0.08")
# STT · Mô tả · Đơn vị · Số lượng · Đơn giá · VAT · Thành tiền · Xóa
_ROW_WIDTHS = [0.4, 3.0, 0.9, 0.9, 1.4, 0.6, 1.3, 0.5]


def _as_number(value: Any) -> float | None:
    """Widget-friendly numeric value (blank stays blank)."""
    if value is None:
        return None
    try:
        return float(str(value))
    except (TypeError, ValueError):
        return None


def _decimal_from_widget(value: Any) -> Decimal | None:
    """Widget floats -> whole Decimal when the value is integral."""
    if value is None:
        return None
    amount = Decimal(str(value))
    if amount == amount.to_integral_value():
        return Decimal(int(amount))
    return amount


def _blank_goods_row() -> dict[str, Any]:
    return {
        "description": "",
        "unit": "",
        "quantity": None,
        "unit_price_vnd_excl_vat": None,
        "vat_rate": _VAT_LOCKED,
    }


def _rows_key(scope: str) -> str:
    return f"docgen_rows_{scope}"


def _rows_to_contract(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Serialise editor rows for storage on the contract record.

    Money is stored as text so no float rounding can ever creep into a legal
    amount and no BSON decimal codec is required.
    """
    out: list[dict[str, Any]] = []
    for row in rows or []:
        out.append(
            {
                "description": str(row.get("description") or "").strip(),
                "unit": str(row.get("unit") or "").strip(),
                "quantity": None if row.get("quantity") is None else str(row.get("quantity")),
                "unit_price_vnd_excl_vat": None if row.get("unit_price_vnd_excl_vat") is None else str(row.get("unit_price_vnd_excl_vat")),
                "vat_rate": "0.08",
            }
        )
    return out


def _contract_to_rows(item: Mapping[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for raw in (item or {}).get("goods_lines") or []:
        if not isinstance(raw, dict):
            continue
        rows.append(
            {
                "description": str(raw.get("description") or ""),
                "unit": str(raw.get("unit") or ""),
                "quantity": _cell_number(raw.get("quantity")),
                "unit_price_vnd_excl_vat": _cell_number(raw.get("unit_price_vnd_excl_vat")),
                "vat_rate": _cell_number(raw.get("vat_rate")) or _VAT_LOCKED,
            }
        )
    return rows


def _goods_rows(scope: str, initial: list[dict[str, Any]] | None) -> list[dict[str, Any]]:
    key = _rows_key(scope)
    stored = st.session_state.get(key)
    if not isinstance(stored, list) or not stored:
        seeded = [dict(row) for row in (initial or [])] or [_blank_goods_row()]
        st.session_state[key] = seeded
        return seeded
    return stored


def _row_amount(row: Mapping[str, Any]) -> Decimal | None:
    quantity = _cell_number(row.get("quantity"))
    price = _cell_number(row.get("unit_price_vnd_excl_vat"))
    if quantity is None or price is None:
        return None
    return (quantity * price).quantize(Decimal("1"), rounding=ROUND_HALF_UP)


def _goods_rows_editor(scope: str, initial: list[dict[str, Any]] | None, *, heading: str = "HÀNG HÓA") -> list[dict[str, Any]]:
    rows = _goods_rows(scope, initial)

    st.markdown(f"#### 🧾 {heading}")
    st.caption("Điền mô tả, đơn vị, số lượng và đơn giá. Để trống số lượng/đơn giá nghĩa là CHƯA BIẾT — hệ thống không tự coi là 0. Thuế GTGT 8% cố định trong V1.")
    header = st.columns(_ROW_WIDTHS)
    for column, text in zip(header, ["STT", "Mô tả hàng hóa", "Đơn vị tính", "Số lượng", "Đơn giá chưa VAT (VND)", "VAT", "Thành tiền chưa VAT", "Xóa"]):
        column.markdown(f"**{text}**")

    for index, row in enumerate(list(rows), start=1):
        cols = st.columns(_ROW_WIDTHS)
        cols[0].markdown(f"**{index}**")  # STT: automatic, read-only
        row["description"] = cols[1].text_input(
            "Mô tả hàng hóa", value=str(row.get("description") or ""),
            key=f"gd_desc_{scope}_{index}", label_visibility="collapsed", placeholder="Mô tả hàng hóa",
        )
        row["unit"] = cols[2].text_input(
            "Đơn vị tính", value=str(row.get("unit") or ""),
            key=f"gd_unit_{scope}_{index}", label_visibility="collapsed", placeholder="Bộ",
        )
        quantity = cols[3].number_input(
            "Số lượng", value=_as_number(row.get("quantity")), min_value=0.0, step=1.0,
            key=f"gd_qty_{scope}_{index}", label_visibility="collapsed", placeholder="SL",
        )
        price = cols[4].number_input(
            "Đơn giá chưa VAT", value=_as_number(row.get("unit_price_vnd_excl_vat")), min_value=0.0, step=1000.0,
            key=f"gd_price_{scope}_{index}", label_visibility="collapsed", placeholder="Đơn giá",
        )
        row["quantity"] = _decimal_from_widget(quantity)
        row["unit_price_vnd_excl_vat"] = _decimal_from_widget(price)
        cols[5].markdown("8%")
        amount = _row_amount(row)
        cols[6].markdown(_money(amount) if amount is not None else "—")
        if cols[7].button("🗑", key=f"gd_del_{scope}_{index}", help=f"Xóa dòng {index}"):
            rows.pop(index - 1)
            if not rows:
                rows.append(_blank_goods_row())
            st.session_state[_rows_key(scope)] = rows
            st.rerun()

    if st.button("➕ THÊM DÒNG HÀNG HÓA", key=f"gd_add_{scope}", type="primary", use_container_width=True):
        rows.append(_blank_goods_row())
        st.session_state[_rows_key(scope)] = rows
        st.rerun()

    return rows


def _goods_totals_block(goods_lines: list[dict[str, Any]]) -> Any:
    totals, _normalized = compute_goods_totals(goods_lines)
    known = total_after_vat(goods_lines) is not None
    m1, m2, m3 = st.columns(3)
    m1.metric("Tiền hàng (chưa VAT)", f"{_money(totals.subtotal) if known else '—'} VND")
    m2.metric("VAT 8%", f"{_money(totals.vat_amount) if known else '—'} VND")
    m3.metric("TỔNG SAU VAT", f"{_money(totals.total_after_vat) if known else '—'} VND")
    return totals


def _path_banner(applicability: Mapping[str, Any]) -> None:
    """Large, business-facing statement of which documents apply."""
    if not goods_totals_known(applicability):
        st.warning("⏳ Chưa có tổng giá trị sau thuế đáng tin cậy, nên chưa thể chọn phương án chứng từ. Hãy điền đủ số lượng và đơn giá ở phần HÀNG HÓA.")
        return
    hdnt_ready = applicability.get(HDNT) is not None and getattr(applicability[HDNT], "state", None) == READY
    hdmb_ready = applicability.get(HDMB) is not None and getattr(applicability[HDMB], "state", None) == READY
    if hdmb_ready:
        st.success("✅ **PHƯƠNG ÁN CHỨNG TỪ:** HỢP ĐỒNG MUA BÁN (HDMB) — vì tổng sau thuế từ 50.000.000 VND trở lên.")
    elif hdnt_ready:
        st.success("✅ **PHƯƠNG ÁN CHỨNG TỪ:** HỢP ĐỒNG NGUYÊN TẮC + PHỤ LỤC (HDNT + PL) — vì tổng sau thuế dưới 50.000.000 VND.")
    else:
        st.info("ℹ️ Chưa có chứng từ nào sẵn sàng. Kiểm tra thẻ trạng thái bên dưới để biết còn thiếu gì.")


def _template_line_warning(applicability: Mapping[str, Any], line_count: int) -> None:
    """Never silently discard goods lines the template cannot carry."""
    hdmb = applicability.get(HDMB)
    if hdmb is not None and getattr(hdmb, "state", None) == BLOCKED and line_count > MAX_HDMB_LINES:
        st.error(
            f"🚫 HDMB V1 hiện chỉ hỗ trợ 1 dòng hàng hóa. "
            f"Hợp đồng này đang có {line_count} dòng. "
            f"Chưa thể xuất file cho đến khi có phương án template phù hợp."
        )
    pl = applicability.get(PL)
    if pl is not None and getattr(pl, "state", None) == BLOCKED and line_count > MAX_PL_LINES:
        st.error(
            f"🚫 Phụ lục (PL) V1 hỗ trợ tối đa {MAX_PL_LINES} dòng hàng hóa. "
            f"Hợp đồng này đang có {line_count} dòng. "
            f"Chưa thể xuất file cho đến khi có phương án template phù hợp."
        )


