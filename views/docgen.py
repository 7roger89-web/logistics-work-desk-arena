def _linked_contract_ids(ship: Mapping[str, Any]) -> list[str]:
    ids: list[str] = []
    for value in [ship.get("contract_id"), ship.get("contract_no")]:
        if value:
            ids.append(str(value).strip().upper())
    for value in ship.get("contract_ids") or []:
        if value:
            ids.append(str(value).strip().upper())
    data = ship.get("data") if isinstance(ship.get("data"), Mapping) else {}
    entrust = data.get("entrustment") if isinstance(data.get("entrustment"), Mapping) else {}
    if entrust.get("active") and entrust.get("contract_no"):
        ids.append(str(entrust.get("contract_no")).strip().upper())
    seen: list[str] = []
    for value in ids:
        if value not in seen:
            seen.append(value)
    return seen


