def _authority_form(kind: str, key_suffix: str = "") -> None:
    """Create-form for a MISSING authority master record.

    ``key_suffix`` keeps widget keys unique when the create form is reachable
    from more than one tab in the same run (Streamlit forbids duplicate keys).
    """
    suffix = f"_{key_suffix}" if key_suffix else ""
    with st.expander(f"➕ Thêm hồ sơ { 'Đại lý' if kind == 'agent' else 'Công ty' }", expanded=False):
        if kind == "company":
            key = st.text_input("Mã Công ty", key=f"doc_company_id{suffix}")
            name = st.text_input("Tên pháp lý", key=f"doc_company_name{suffix}")
            addr = st.text_input("Địa chỉ pháp lý", key=f"doc_company_addr{suffix}")
            code = st.text_input("Mã số thuế", key=f"doc_company_code{suffix}")
            rep = st.text_input("Người đại diện", key=f"doc_company_rep{suffix}")
            title = st.text_input("Chức vụ", key=f"doc_company_title{suffix}")
            if st.button("Lưu Công ty", key=f"doc_company_save{suffix}"):
                ok = save_authority_company({
                    "company_id": key.strip().upper(),
                    "legal_name": name,
                    "legal_address": addr,
                    "tax_or_legal_code": code,
                    "legal_representative": rep,
                    "representative_title": title,
                })
                st.success("Đã lưu.") if ok else st.error("Không lưu được.")
        else:
            key = st.text_input("Mã Đại lý", key=f"doc_agent_id{suffix}")
            name = st.text_input("Tên pháp lý", key=f"doc_agent_name{suffix}")
            addr = st.text_input("Địa chỉ pháp lý", key=f"doc_agent_addr{suffix}")
            code = st.text_input("Mã số thuế / pháp lý", key=f"doc_agent_code{suffix}")
            rep = st.text_input("Người đại diện", key=f"doc_agent_rep{suffix}")
            title = st.text_input("Chức vụ", key=f"doc_agent_title{suffix}")
            bank_holder = st.text_input("Chủ tài khoản", key=f"doc_agent_bank_holder{suffix}")
            bank_no = st.text_input("Số tài khoản", key=f"doc_agent_bank_no{suffix}")
            bank_name = st.text_input("Ngân hàng", key=f"doc_agent_bank_name{suffix}")
            if st.button("Lưu Đại lý", key=f"doc_agent_save{suffix}"):
                ok = save_authority_agent({
                    "agent_id": key.strip().upper(),
                    "legal_name": name,
                    "legal_address": addr,
                    "legal_code_type": "MST",
                    "legal_code": code,
                    "legal_representative": rep,
                    "representative_title": title,
                    "bank_account_holder": bank_holder,
                    "bank_account_number": bank_no,
                    "bank_name": bank_name,
                })
                st.success("Đã lưu.") if ok else st.error("Không lưu được.")
